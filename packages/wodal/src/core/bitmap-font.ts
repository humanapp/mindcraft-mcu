/**
 * Returns the five row bytes for `charCode`, or the space glyph when the code
 * is outside {@link FONT_ASCII_START}..{@link FONT_ASCII_END}.
 */
export function fontGlyphRows(charCode: number): readonly number[] {
  const code = charCode >= FONT_ASCII_START && charCode <= FONT_ASCII_END ? charCode : FONT_ASCII_START;
  const offset = (code - FONT_ASCII_START) * FONT_GLYPH_SIZE;
  return FONT_ROWS.slice(offset, offset + FONT_GLYPH_SIZE);
}
